  // --- actions ---
  async function act(route,extra){
    if(busy)return;busy=true;syncControls();bringIntoView();
    markTipSeen(stageOf());
    [].slice.call(actionbar.querySelectorAll('.coach-tip')).forEach(function(t){t.remove()});
    [].slice.call(actionbar.querySelectorAll('.pulse')).forEach(function(b){b.classList.remove('pulse')});
    [].slice.call(demo.querySelectorAll('.derr,.dnote')).forEach(function(e){e.remove()});
    var progress=el('div','dprogress'),msg=el('div','dsub',WORKING[route]);msg.setAttribute('role','status');
    progress.appendChild(el('div','bar'));progress.appendChild(msg);actionbar.appendChild(progress);
    var res=await api('POST',route,Object.assign({objective:objSel.value||undefined},extra||{}));
    busy=false;
    if(!res.network&&res.status===409&&await refreshFromServer()){
      viewing=null;renderAll();
      note('The copy of this demo saved in your browser was out of date, so it has been refreshed. Continue from here.');
    }else if(res.network||!res.ok){
      progress.remove();syncControls();
      var err=el('div','derr',res.network?'Could not reach the demo API. Please check your connection and try again.':(res.body.error||'Something went wrong.'));
      if(res.body&&res.body.attempts&&res.body.attempts.length){
        err.appendChild(el('div','dsub',res.body.attempts.length+(res.body.attempts.length===1?' attempt':' attempts')+'. Output that fails a check is never shown.'));
      }
      actionbar.appendChild(err);
    }else{
      state=res.body;saveState();viewing=null;renderAll();bringIntoView();
    }
  }
  // Keep the whole demo frame on screen while it is in use. On laptops the frame is sized to the window, so
  // this lines it up under the site navigation; on phones it brings the top of the new step into view.
  function bringIntoView(force){
    var nav=document.querySelector('.nav'),top=(nav?nav.getBoundingClientRect().height:0)+12,r=demo.getBoundingClientRect();
    if(force||r.top<top-1||r.bottom>innerHeight+1){
      // Layout position, not the on-screen one, so the section's fade-in offset does not throw off the alignment.
      var y=0;for(var n=demo;n;n=n.offsetParent)y+=n.offsetTop;
      scrollTo({top:y-top,behavior:matchMedia('(prefers-reduced-motion: reduce)').matches?'auto':'smooth'});
    }
  }

  // --- one-time tour: one popover at a time under the row it explains, the first time the demo is in view ---
  function tourDone(){try{return localStorage.getItem('signalloop-tour')==='done'}catch(e){return false}}
  function startTour(){if(tourStep>=0||tourDone())return;tourStep=0;showTour()}
  function endTour(){
    try{localStorage.setItem('signalloop-tour','done')}catch(e){}
    tourStep=-1;
    if(tourEl){tourEl.remove();tourEl=null}
    if(tourAnchor){tourAnchor.classList.remove('tour-on');tourAnchor=null}
    if(!busy){renderPanel();syncControls()}
  }
  function showTour(){
    var s=TOUR[tourStep],last=tourStep===TOUR.length-1;
    if(tourAnchor)tourAnchor.classList.remove('tour-on');
    tourAnchor=$(s[0]);tourAnchor.classList.add('tour-on');
    if(!tourEl){tourEl=el('div','tour');tourEl.setAttribute('role','dialog');tourEl.setAttribute('aria-label','Demo tour');demo.appendChild(tourEl)}
    tourEl.textContent='';
    tourEl.appendChild(el('div','tour-k',(tourStep+1)+' of '+TOUR.length));
    tourEl.appendChild(el('b','tour-t',s[1]));tourEl.appendChild(el('p',null,s[2]));
    var row=el('div','tour-row'),next=el('button','coach-x',last?'Got it':'Next');next.type='button';
    next.addEventListener('click',function(){if(last)endTour();else{tourStep++;showTour()}});
    if(!last){var skip=el('button','tour-skip','Skip tour');skip.type='button';skip.addEventListener('click',endTour);row.appendChild(skip)}
    row.appendChild(next);tourEl.appendChild(row);placeTour();
  }
  // Places the popover just under its row, with the pointer near the row's start.
  function placeTour(){
    if(!tourEl||!tourAnchor)return;
    var d=demo.getBoundingClientRect(),a=tourAnchor.getBoundingClientRect(),left=Math.max(12,Math.min(a.left-d.left,d.width-tourEl.offsetWidth-12));
    tourEl.style.top=(a.bottom-d.top+12)+'px';tourEl.style.left=left+'px';
    tourEl.style.setProperty('--arrow',Math.max(18,a.left-d.left+Math.min(28,a.width/2)-left)+'px');
  }
